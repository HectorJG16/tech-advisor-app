from __future__ import annotations

VERIFIED_DATE = "2026-09-21"


def _steps(items: list[tuple[str, str]]) -> list[dict]:
    return [
        {"step": index, "title": title, "description": description}
        for index, (title, description) in enumerate(items, start=1)
    ]


def _src(field: str, url: str, notes: str | None = None) -> dict:
    return {
        "field_name": field,
        "source_url": url,
        "last_verified": VERIFIED_DATE,
        "notes": notes,
    }


